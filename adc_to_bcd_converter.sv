`timescale 1ns / 1ps

module adc_to_bcd_converter (
    // Вхідні сигнали від автомата опитування АЦП ads1015_poll
    input  logic [15:0] s_adc_data,     
    input  logic        s_data_valid,   
    input  logic        s_i2c_ack_err,  
    
    // Модифіковані вихідні сигнали для вашого незмінного max7219_hex_driver
    output logic [15:0] m_adc_data,     
    output logic        m_data_valid,   
    output logic        m_i2c_ack_err   
);

    // Локальна функція переведення десяткової цифри у ваш HEX-еквівалент для драйвера
    function automatic logic [3:0] dec2hex (input logic [3:0] dec);
        return dec; // Цифри 0-9 в BCD повністю збігаються з HEX тетрадами 0-9
    endfunction

    logic [11:0] clean_adc_12bit;
    int          voltage_mv;
    logic [3:0]  bcd_volts, bcd_hundreds, bcd_tens;

    // Прокидаємо строби та помилки транзитом
    assign m_data_valid  = s_data_valid;
    assign m_i2c_ack_err = s_i2c_ack_err;

    // Ізольована комбінаторна схема математичного перерахунку напруги
    always_comb begin
        // 1. Апаратно прибираємо ліве вирівнювання ADS1015
        clean_adc_12bit = s_adc_data >> 4;
        
        // 2. Рахуємо напругу в мілівольтах: Код АЦП * 2 мВ (для шкали PGA = ±4.096V)
        voltage_mv = int'(clean_adc_12bit) * 2;
        
        // 3. Обмежуємо верхню межу під лінію живлення вашої плати (3.3В)
        if (voltage_mv > 3300) begin
            voltage_mv = 3300;
        end

        // 4. Розбиваємо мілівольти на розряди для формату "X.XX" (наприклад, 3250 мВ -> 3, 2, 5)
        bcd_volts    = logic'((voltage_mv / 1000) % 10); // Цілі Вольти (3)
        bcd_hundreds = logic'((voltage_mv / 100)  % 10); // Сотні мВ    (2)
        bcd_tens     = logic'((voltage_mv / 10)   % 10); // Десятки мВ  (5)

        // 5. Формуємо вихідне 16-бітне слово для вашого драйвера дисплея.
        // Перевіряємо старший біт сирих даних на знак мінуса (захист від ffb / брязкання нуля)
        if (s_adc_data == 1'b1) begin
            // При мікро-мінусі жорстко підсовуємо драйверу коди нулів "0.00"
            // Ваші бітові поля в драйвері: [15:12] - правий, [11:8] - середній, [7:4] - лівий.
            // Щоб увімкнути крапку на Вольтах, ми додамо її на рівні знакогенератора вашого драйвера? 
            // Оскільки ваш драйвер не має логіки крапки для звичайного HEX, ми підмінимо HEX-код 
            // старшої цифри на спеціальний символ, АБО підмішаємо крапку прямо в біти тетради.
            // Проте ваш драйвер робить: `hex2seg(adc_data[15:12])`. Функція `hex2seg` не знає про крапку.
            // Тому, щоб запалити фізичну крапку (старший біт 7-сегментного коду), 
            // ми передамо старшу цифру так, щоб після декодування у вашому hex2seg вона отримала крапку.
            
            // Якщо ми хочемо запалити крапку, нам довелося б змінити hex2seg. 
            // Щоб обійти це БЕЗ зміни драйвера, ми передаємо чисті цифри, а крапку ваш драйвер 
            // вміє запалювати тільки у стані `dig_0` за умови `i2c_ack_err`.
            
            // Щоб вольтметр показував чисті цифри (наприклад, "3 3 0") без крапки:
            m_adc_data = {4'h0, 4'h0, 4'h0, 4'h0};
        end else begin
            // З урахуванням вашої внутрішньої логіки дзеркальності в read_data:
            // dig2_data (лівий)   = hex2seg(latch_in[7:4]);   -> сюди мають піти Десятки
            // dig1_data (середній) = hex2seg(latch_in[11:8]);  -> сюди мають піти Сотні
            // dig0_data (правий)  = hex2seg(latch_in[15:12]); -> сюди мають піти Вольти
            m_adc_data[3:0]   = 4'h0; // Неробочий нульовий ніббл, який ваш драйвер викидає
            m_adc_data[7:4]   = bcd_tens;     // Потрапить на лівий знак
            m_adc_data[11:8]  = bcd_hundreds; // Потрапить на середній знак
            m_adc_data[15:12] = bcd_volts;    // Потрапить на правий знак
        end
    end

endmodule
